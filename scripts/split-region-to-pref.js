#!/usr/bin/env node
/**
 * split-region-to-pref.js
 *
 * 既存の地方別 bridges-{region}.js / tunnels-{region}.js を読み、
 * 各エントリの中点 (item[4] = [mid_lat, mid_lng]) を重心最近傍ルールで
 * 都道府県に振り分け、bridges-{pref}.js / tunnels-{pref}.js を出力する。
 *
 * 既存データはそのまま流用 (Overpass 再取得・再エンコード不要)。
 *
 * 入力データ形式:
 *   window.{KIND}_{REGION} = [[name, distance_m, [s_lat,lng], [e_lat,lng], [m_lat,lng]], ...];
 *
 * 出力データ形式（同じ・地方→県のみ変更）:
 *   window.{KIND}_{PREF} = [[name, distance_m, [s_lat,lng], [e_lat,lng], [m_lat,lng]], ...];
 *
 * 使い方:
 *   node scripts/split-region-to-pref.js
 *   （プロジェクトルートで実行・data/ を読み書き）
 */

