#!/usr/bin/env node
/**
 * build-road-attrs.js
 *
 * 道路属性（緊急輸送道路・スクールゾーン）を road-attrs-{pref}.js に出力する。
 *
 * 使い方:
 *   node scripts/build-road-attrs.js <pref> <emergency.geojson> <school.geojson>
 *   ex: node scripts/build-road-attrs.js ehime input/ehime/emergency.geojson input/ehime/school.geojson
 *
 * 入力 GeoJSON 仕様:
 *   FeatureCollection。各 Feature は properties に
 *     - "roadIndices": [int, int, ...]   既存 roads-{pref}.js の roadIdx 列を直接指定
 *     - "roadIndex": int                 単一 roadIdx
 *   のいずれかを持つ。これがあれば spatial matching をスキップして使う。
 *   無い場合は空ファイルを出力する（spatial matching は v2 で実装予定）。
 */

const fs = require('fs');
const path = require('path');
const { encodeIndexListB64 } = require('./encoding-utils.js');

const [, , PREF, EMERGENCY_PATH, SCHOOL_PATH] = process.argv;
if (!PREF) {
  console.error('Usage: build-road-attrs.js <pref> [emergency.geojson] [school.geojson]');
  process.exit(1);
}

function collectIndices(filePath) {
  if (!filePath || !fs.existsSync(filePath)) {
    console.log(`  (skip) ${filePath || 'なし'}`);
    return [];
  }
  const geo = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  if (!geo.features) throw new Error(`Invalid GeoJSON: ${filePath}`);
  const indices = new Set();
  let withSpec = 0,
    withoutSpec = 0;
  for (const f of geo.features) {
    const props = f.properties || {};
    if (Array.isArray(props.roadIndices)) {
      for (const idx of props.roadIndices) indices.add(idx | 0);
      withSpec++;
    } else if (typeof props.roadIndex === 'number') {
      indices.add(props.roadIndex | 0);
      withSpec++;
    } else {
      withoutSpec++;
    }
  }
  console.log(
    `  ${path.basename(filePath)}: features=${geo.features.length} (with-roadIndices=${withSpec}, without=${withoutSpec}) → unique idx=${indices.size}`
  );
  return [...indices];
}

console.log(`[build-road-attrs] prefecture=${PREF}`);

// roads-{pref}.js から numRoads を読む（必須整合性チェック）
const roadsPath = path.join(__dirname, '..', 'data', `roads-${PREF}.js`);
let numRoads = 0;
if (fs.existsSync(roadsPath)) {
  const text = fs.readFileSync(roadsPath, 'utf8');
  const m = text.match(/"numRoads":(\d+)/);
  if (m) numRoads = parseInt(m[1], 10);
}
console.log(`  roads-${PREF}.js numRoads=${numRoads}`);

const emergency = collectIndices(EMERGENCY_PATH);
const school = collectIndices(SCHOOL_PATH);

// 範囲外チェック
function clamp(arr, label) {
  if (numRoads === 0) return arr;
  const filtered = arr.filter((i) => i >= 0 && i < numRoads);
  if (filtered.length !== arr.length) {
    console.warn(
      `  ⚠️ ${label}: 範囲外 ${arr.length - filtered.length} 件をスキップ（numRoads=${numRoads}）`
    );
  }
  return filtered;
}
const emergencyClean = clamp(emergency, 'emergency');
const schoolClean = clamp(school, 'school');

const out = {
  v: 1,
  type: 'road-attrs',
  prefecture: PREF,
  generated: new Date().toISOString(),
  numRoads: numRoads,
  emergencyRouteB64: encodeIndexListB64(emergencyClean),
  schoolZoneB64: encodeIndexListB64(schoolClean),
  counts: { emergency: emergencyClean.length, school: schoolClean.length },
};

const VAR = `ROAD_ATTRS_${PREF.toUpperCase().replace(/-/g, '_')}`;
const header = [
  `// Auto-generated by scripts/build-road-attrs.js`,
  `// Prefecture: ${PREF}`,
  `// Generated: ${out.generated}`,
  `// 形式: emergencyRouteB64 / schoolZoneB64 = sorted roadIdx 列を delta-varint-base64`,
  `window.${VAR} = ${JSON.stringify(out)};`,
  '',
].join('\n');

const outPath = path.join(__dirname, '..', 'data', `road-attrs-${PREF}.js`);
fs.writeFileSync(outPath, header);
const size = fs.statSync(outPath).size;
console.log(`✅ ${outPath}`);
console.log(
  `  emergency=${emergencyClean.length} / school=${schoolClean.length} / size=${(size / 1024).toFixed(2)} KB`
);
