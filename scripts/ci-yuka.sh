#!/bin/sh
# ci-yuka.sh — 自己確認の 出しが 床に 届いているかを 見る（CI の 全部の 床を ここ 1 か所で・2026-10-11）
#
#   使い方:  sh scripts/ci-yuka.sh 出しの紙 組の床 [回数の床]
#            sh scripts/ci-yuka.sh --self-test
#   緑の 時だけ 0。
#     「自己確認: a/b」の 行が ちょうど 1 本・a と b が 数字だけ・a = b・a ≥ 組の床
#     回数の床を 渡した 時は「確かめた 回数: c」の 行も ちょうど 1 本・c が 数字だけ・c ≥ 回数の床
#   ★前の 形（awk の $3 + 0）は「234x」の 様な 字も 数として 通した★（ゼイマリーの 対立役の 測り・10-11）。
#   ★床を 割ったら 赤を ubuntu の awk（mawk）で 確かめる★＝--self-test を CI で 回す（233・234x 等）
set -u

yuka() {
  f=$1
  g=$2
  c=${3:-}
  awk -F'[ /]' -v g="$g" '
    /^自己確認: / { n++; if (NF == 3 && $2 ~ /^[0-9]+$/ && $3 ~ /^[0-9]+$/ && $2 + 0 == $3 + 0 && $2 + 0 >= g + 0) ok++ }
    END { exit !(n == 1 && ok == 1) }' "$f" || {
    echo "✗ 床: 自己確認の 行が 床（$g 組）に 届かない・形が 違う・1 本で ない（$f）"
    return 1
  }
  if [ -n "$c" ]; then
    awk -v c="$c" '
      /^確かめた 回数: / { n++; if (NF == 3 && $3 ~ /^[0-9]+$/ && $3 + 0 >= c + 0) ok++ }
      END { exit !(n == 1 && ok == 1) }' "$f" || {
      echo "✗ 床: 確かめた 回数の 行が 床（$c 回）に 届かない・形が 違う・1 本で ない（$f）"
      return 1
    }
  fi
  echo "✓ 床: $f は $g 組${c:+・$c 回} 以上"
}

self_test() {
  d=$(mktemp -d)
  pass=0
  fail=0
  # 期待（0＝緑・1＝赤）・字
  t() {
    want=$1
    shift
    printf '%s\n' "$@" >"$d/o"
    if yuka "$d/o" 29 239 >/dev/null; then got=0; else got=1; fi
    if [ "$got" = "$want" ]; then pass=$((pass + 1)); else
      fail=$((fail + 1))
      echo "  ✗ 期待 $want・実際 $got：$*"
    fi
  }
  t 0 "自己確認: 29/29" "確かめた 回数: 239"
  t 0 "  ✓ 何か" "自己確認: 30/30" "確かめた 回数: 300"
  t 1 "自己確認: 29/29" "確かめた 回数: 238"
  t 1 "自己確認: 29/29" "確かめた 回数: 233"
  t 1 "自己確認: 29/29" "確かめた 回数: 239x"
  t 1 "自己確認: 29/29" "確かめた 回数: 2390x"
  t 1 "自己確認: 29/29" "確かめた 回数: 239 x"
  t 1 "自己確認: 29/29" "確かめた 回数: "
  t 1 "自己確認: 29/29"
  t 1 "自己確認: 28/29" "確かめた 回数: 300"
  t 1 "自己確認: 28/28" "確かめた 回数: 300"
  t 1 "自己確認: 29/29x" "確かめた 回数: 239"
  t 1 "自己確認: 29x/29" "確かめた 回数: 239"
  t 1 "自己確認: 29/29/29" "確かめた 回数: 239"
  t 1 "自己確認: 29/29" "確かめた 回数: 239" "自己確認: 29/29"
  t 1 "自己確認: 29/29" "確かめた 回数: 239" "確かめた 回数: 239"
  t 1 "確かめた 回数: 239"
  t 1
  # 回数の床を 渡さない（メールの門）＝組だけ 見る
  printf '%s\n' "自己確認: 5/5" >"$d/m"
  if yuka "$d/m" 5 >/dev/null; then pass=$((pass + 1)); else
    fail=$((fail + 1))
    echo "  ✗ 回数の 床 無しで 5/5 が 赤"
  fi
  printf '%s\n' "自己確認: 5/5x" >"$d/m"
  if yuka "$d/m" 5 >/dev/null; then
    fail=$((fail + 1))
    echo "  ✗ 回数の 床 無しで 5/5x が 緑"
  else pass=$((pass + 1)); fi
  rm -rf "$d"
  echo "自己確認: $pass/$((pass + fail))"
  [ "$fail" = 0 ]
}

if [ "${1:-}" = "--self-test" ]; then
  self_test
  exit $?
fi
[ $# -ge 2 ] || {
  echo "使い方: sh scripts/ci-yuka.sh 出しの紙 組の床 [回数の床]"
  exit 2
}
yuka "$@"
