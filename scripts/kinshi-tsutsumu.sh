#!/usr/bin/env bash
# ============================================================
# scripts/kinshi-tsutsumu.sh
# ★実在の字の見張りを 包んで 走らせ、公開の ログには 一覧の 番号も 当たった 場所も 出さない★ 2026-10-16（つなぎ）
#
#   見張りの 本体（tests/kinshi-ji.test.mjs）は 他の 席の 写しで、赤の 時に「道:行: 一覧の N 番目」等を 出す。
#   公開 repo の CI の ログは 誰でも 読めるので、どの ファイルの どこが 一覧の 何番目に 当たったかが 残った
#   （指示役の 決めで その ログ 6本を 消した）。本体の 直しが 写しとして 届くまでの つなぎ。
#
#   ★逆の 作り★（対立役：漏れそうな 番号の 形を 並べて 伏せる 作りは、字が 少し 変わると 黙って 漏れる。
#     しかも ubuntu の sed は 全角の 範囲で 落ちて、伏せた 写しが 一度も 出ていなかった）
#     「一覧」を 含む 行は 丸ごと ログに 出さない（通すのは 本体の 見出し「node v…」と「✗ 一覧の 指紋が 違う」の 行だけ）。
#     比べるのは バイト（LC_ALL=C・awk の index）＝locale にも 字の 範囲にも 左右されない。
#     伏せた 行は 道ごとの 件数だけ 出す（道の 名前に 当たった 行・何本目 で 出る 行は 道も 出さない）。
#   ★判じは 今まで通り 全文（kinshi.out）で 行う★＝伏せた 写しで 判じない。
#   ★kinshi.out は どこにも 出さない★（成果物にも ログにも）。job の 終わりで 消えるだけ。
#   ★赤の 日は 必ず「見張りが 赤・伏せた行 N 本・道ごとの 件数」を 出す★（赤なのに ログが 空 を 作らない）
#
#   使い方：bash scripts/kinshi-tsutsumu.sh [見張りの 命令…]（省けば npm run kinshi）。出しの 置き場は KINSHI_OUT（既定 kinshi.out）
#   終わり値：見張りが 緑（終わり値 0 かつ「✓ 実在の 字 0 件」の 行が 在る）なら 0・それ以外は 1
# ============================================================
set -u
OUT="${KINSHI_OUT:-kinshi.out}"
if [ "$#" -gt 0 ]; then
  "$@" > "$OUT" 2>&1
else
  npm run kinshi > "$OUT" 2>&1
fi
rc=$?
if [ "$rc" -eq 0 ] && grep -q "^✓ 実在の 字 0 件" "$OUT"; then
  midori=1
else
  midori=0
fi
# ログに 出すのは 「一覧」を 含む 行を 除いた 写しと、伏せた 行の 本数・道ごとの 件数
if ! LC_ALL=C awk -v midori="$midori" '
  function michi(s,   t, i) {
    t = s
    sub(/^[ \t]*赤(（未測定）)?:[ \t]*/, "", t)
    if (index(t, "追跡物の") == 1 || substr(t, 1, 1) == "(") return "（名前に当たる道・道は出さない）"
    i = index(t, ":"); if (i > 0) t = substr(t, 1, i - 1)
    i = index(t, " "); if (i > 0) t = substr(t, 1, i - 1)
    i = index(t, "("); if (i > 0) t = substr(t, 1, i - 1)
    return (t == "" ? "（道が読めない）" : t)
  }
  # 通すのは 本体の 見出し（頭が「node v」）と「✗ 一覧の 指紋が 違う」の 2つだけ。他で「一覧」を 含む 行は 全部 伏せる
  #   （「指紋」の 字で 通すと、道の 名前に「指紋」が 在る 当たりの 行が そのまま 出た・対立役）
  index($0, "一覧") && index($0, "node v") != 1 && index($0, "✗ 一覧の 指紋が 違う") != 1 { n++; c[michi($0)]++; next }
  { print }
  END {
    if (midori != 1) {
      printf "✗ 実在の字の見張りが 赤・伏せた行 %d 本（一覧の 番号と 当たった 場所は ログに 出さない・判じは 全文で 行った）\n", n
      for (k in c) printf "  伏せた行: %s %d 本\n", k, c[k]
    } else if (n > 0) {
      printf "（一覧を 含む 行 %d 本は ログに 出さない）\n", n
    }
  }
' "$OUT"; then
  echo "✗ ログの 写しを 作れなかった（判じは 全文で 行う・中身は 出さない）"
fi
[ "$midori" -eq 1 ] && exit 0
exit 1
