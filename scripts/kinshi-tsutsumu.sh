#!/usr/bin/env bash
# ============================================================
# scripts/kinshi-tsutsumu.sh
# ★実在の字の見張りを 包んで 走らせ、公開の ログには 一覧の 番号を 出さない★ 2026-10-16（つなぎ）
#
#   見張りの 本体（tests/kinshi-ji.test.mjs）は 他の 席の 写しで、赤の 時に「道:行: 一覧の N 番目」を 出す。
#   公開 repo の CI の ログは 誰でも 読めるので、どの ファイルが 一覧の 何番目に 当たったかの 組が 残った
#   （指示役の 決めで その ログ 5本を 消した）。本体の 直しが 写しとして 届くまでの つなぎ。
#
#   ★判じは 今まで通り 全文（kinshi.out）で 行う★＝伏せた 写しで 判じない（伏せる 置き換えが 当たり行を 消して
#     緑に 見える 形を 作らない 為）。
#   ★kinshi.out は どこにも 出さない★（成果物にも ログにも）。job の 終わりで 消えるだけ。
#
#   使い方：bash scripts/kinshi-tsutsumu.sh [見張りの 命令…]（省けば npm run kinshi）
#   終わり値：見張りが 緑（終わり値 0 かつ「✓ 実在の 字 0 件」の 行が 在る）なら 0・それ以外は 1
# ============================================================
set -u
OUT="${KINSHI_OUT:-kinshi.out}"
if [ "$#" -gt 0 ]; then
  "$@" > "$OUT" 2>&1
else
  npm run kinshi > "$OUT" 2>&1
fi
rc=$?
# ログに 出すのは 番号を 伏せた 写しだけ（「一覧の N 番目」の N を 消す）
sed -E 's/一覧の[[:space:]]*[0-9０-９]+[[:space:]]*番目/一覧の（番号は伏せた）/g' "$OUT"
if [ "$rc" -eq 0 ] && grep -q "^✓ 実在の 字 0 件" "$OUT"; then
  exit 0
fi
echo "✗ 実在の字の見張りが 赤（番号は ログに 出さない・判じは 全文で 行った）"
exit 1
