//   ★何を 消したか（2026-08-30・司さん「課金距離変わらんならやれや」）★
//     data/road-graph-<県>.js …………… 47本 1,023 MB
//     data/road-graph-tiles/<県>/…… 15,896本 約1,090 MB
//     ＝合計 ★約2.1GB★（repo 3.22GB の 65%）
//
//   ★なぜ 消してよいと 判断したか（全部 数えた）★
//     ・客側（index.html / sw.js / js/*.js）に `road-graph-tiles` … ★0箇所★
//     ・客側で `road-graph-<県>.js` を 呼ぶ 所 …………………………… ★0箇所★
//       （使うのは road-graph-backbone-jp.js だけ。★これは 残しています★）
//     ・試験で 使う 所 ……………………………………………………………… ★0本★
//     ・画面の 注記「★旧 region-loader.js / road-graph-tile-loader.js（2026-05-13 大改修 C11）★」
//       ＝★読む 仕組みは その時に 外れ、データだけ 残っていました★
//
//   ★作り直せます★
//     どちらも 頭に「Auto-generated by scripts/build-road-graph(-tiled).js」と 書いてあり、
//     元(data/roads-<県>.js)も 作る道具(scripts/)も ★repo に 残っています★。
//     さらに ★git の 履歴に そのまま 残ります★（いつでも 取り出せます）。
//
//   ★ここで 見る事★
//     ①消した物を ★客側が 呼び始めていない★（呼ぶなら データが 無いので 壊れます）
//     ②★作り直す道具★が 残っている
//     ③★元のデータ★(roads-<県>.js)が 残っている
