const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const DATA = path.join(ROOT, 'data');

function kokyakuSrc() {
  let s = '';
  for (const p of ['index.html', 'sw.js']) {
    const fp = path.join(ROOT, p);
    if (fs.existsSync(fp)) s += fs.readFileSync(fp, 'utf8') + '\n';
  }
  const jsDir = path.join(ROOT, 'js');
  for (const f of fs.readdirSync(jsDir)) {
    if (f.endsWith('.js')) s += fs.readFileSync(path.join(jsDir, f), 'utf8') + '\n';
  }
  // ★注記は 外す★（説明の 中の 名前で 赤に しない）
  return s.replace(/^\s*(\/\/|\*|<!--).*$/gm, '');
}

describe('★使っていない 道路グラフを repo に 戻さない（Vercel の お金）★', () => {
  const src = kokyakuSrc();

  it('★① 客側が road-graph-tiles を 呼んでいない★', () => {
    expect(
      src.includes('road-graph-tiles'),
      '★消したデータを 呼んでいます（データが 無いので 壊れます）★'
    ).toBe(false);
  });

  it('★② 客側が road-graph-<県>.js を 呼んでいない（backbone は 別）★', () => {
    // ★2026-08-30 直し★: はじめ `road-graph-[a-z]+` で 探して
    //   ★作る道具の 名前（build-road-graph-tiled.js）まで 拾って 赤に なりました★。
    //   ⇒★data/ の 物だけ★を 見ます（呼んでいるか、を 見たいので）。
    const hits = (src.match(/\/data\/road-graph-[a-z-]+/g) || []).filter(
      (x) => !x.startsWith('/data/road-graph-backbone')
    );
    expect(hits, '★県ごとの 道路グラフを 呼んでいます★').toEqual([]);
  });

  it('★③ 作り直す 道具が 残っている★', () => {
    ['build-road-graph.js', 'build-road-graph-tiled.js'].forEach((f) => {
      expect(fs.existsSync(path.join(ROOT, 'scripts', f)), '★作り直せません: ' + f + '★').toBe(
        true
      );
    });
  });

  it('★④ 元のデータ(roads-<県>.js)が 残っている★', () => {
    const roads = fs.readdirSync(DATA).filter((f) => /^roads-[a-z]+\.js$/.test(f));
    expect(roads.length, '★元のデータが 足りません（作り直せません）★').toBeGreaterThanOrEqual(47);
  });

  it('★⑤ 使っている backbone は 消していない★', () => {
    expect(
      fs.existsSync(path.join(DATA, 'road-graph-backbone-jp.js')),
      '★使っている 道路グラフを 消しました★'
    ).toBe(true);
    expect(src, '★backbone を 呼ぶ 所が 消えました★').toContain('road-graph-backbone-jp.js');
  });

  it('★★⑥ 消した物が repo に 戻ってきていない★★', () => {
    expect(
      fs.existsSync(path.join(DATA, 'road-graph-tiles')),
      '★タイルが 戻っています（また 3.2GB に なります）★'
    ).toBe(false);
    const kenGoto = fs
      .readdirSync(DATA)
      .filter((f) => /^road-graph-[a-z]+\.js$/.test(f) && f !== 'road-graph-backbone-jp.js');
    expect(kenGoto, '★県ごとの 道路グラフが 戻っています★').toEqual([]);
  });
});
