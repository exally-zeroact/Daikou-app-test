'use strict';

const fs = require('fs');
const path = require('path');

const HTML = fs.readFileSync(path.join(__dirname, '..', '..', 'kyuryo.html'), 'utf8');

// 「給料の設定」タブの 中の「車の売上」の 箱だけ 切り出す
function kurumaHako() {
  const i = HTML.indexOf('給料明細に 出す 車の 売上');
  if (i < 0) return '';
  return HTML.slice(i, i + 2600);
}

describe('★車ごとの売上の 決めごとを 1か所に★', () => {
  it('★① 箱の 名前が「給料明細に 出す 車の 売上」に なっている★', () => {
    expect(HTML, '★箱の 名前が ありません★').toContain('給料明細に 出す 車の 売上');
  });

  it('★★② 会社ぜんぶの チェックが その箱の 中に 在る★★', () => {
    expect(kurumaHako(), '★チェックが 別の 場所に 在ります★').toMatch(/id="showCarSales"/);
  });

  it('★★③ チェックは 1か所だけ（2つ 置かない）★★', () => {
    const kazu = (HTML.match(/id="showCarSales"/g) || []).length;
    expect(kazu, '★チェックが ' + kazu + ' 箇所 在ります★').toBe(1);
  });

  it('★④ 人ごと（従業員タブ）へ 1押しで 飛べる★', () => {
    expect(kurumaHako(), '★従業員タブへ 飛ぶボタンが ありません★').toMatch(/id="toEmpTab"/);
    expect(HTML, '★飛ぶボタンが 何も していません★').toMatch(
      /getElementById\('toEmpTab'\)[\s\S]{0,400}data-tab="emp"/
    );
  });

  it('★⑤ 保存する 中身は 変えていない（棚も 名前も そのまま）★', () => {
    expect(HTML, '★会社ぜんぶの 設定を 保存していません★').toMatch(
      /show_car_sales:\s*\$\('showCarSales'\)\.checked/
    );
    expect(HTML, '★車ごとの 設定が 消えました★').toContain('show_in_slip');
    expect(HTML, '★人ごとの 設定が 消えました★').toContain('slip_cars');
  });
});
